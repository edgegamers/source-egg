#!/usr/bin/env python3
"""Generate embedded terminal glyphs from the two approved branding assets.
Requires Pillow only when regenerating; the compiled node needs no image tools.
"""
from pathlib import Path
from PIL import Image

root = Path(__file__).resolve().parent.parent

def art(path, width, edge=False):
    image = Image.open(path).convert('RGBA').resize((width, 24), Image.Resampling.LANCZOS)
    glyphs, colors = [], []
    for y in range(0, 24, 2):
        row, color = '', ''
        for x in range(width):
            top, bottom = image.getpixel((x,y)), image.getpixel((x,y+1))
            lit = lambda p: p[3] > 100 and (not edge or sum(p[:3]) > 380)
            a, b = lit(top), lit(bottom)
            row += '█' if a and b else '▀' if a else '▄' if b else ' '
            px = top if a else bottom
            color += 'o' if (a or b) and px[0] > 150 and px[1] < 200 and px[2] < 120 else 'w'
        glyphs.append(row)
        colors.append(color)
    return glyphs, colors

out = ['// Code generated by scripts/generate-terminal-art.py; DO NOT EDIT.', 'package terminalui', '']
for name, path, width, edge in [('edgeLogo','assets/edgegamers-mark.webp',36,True),('sourceLogo','assets/source-logo.png',24,False)]:
    glyphs, colors = art(root/path,width,edge)
    for suffix, rows in [('',glyphs),('Colors',colors)]:
        out.append('var '+name+suffix+' = []string{')
        out.extend('\t"'+row+'",' for row in rows)
        out.append('}')
(root/'internal/terminalui/logos.go').write_text('\n'.join(out)+'\n')
